#!/usr/bin/env python3
"""The Python engine's sign-off on the golden corpus -- its last act before deletion.

    uv run python tools/verify_corpus.py

PLAN.md §14.1, Phase 3.1 step 1. `tests/golden/corpus/` is generated by the Rust build
frozen as `oracle-v1` (`cargo run -p ttr-tools --bin gen-corpus -- --write`). This script
recomputes every game in it with the **Python** engine and the **Python** encoder, sharing
no code with the Rust side beyond the board data both are generated from, and fails on the
first disagreement. It is deleted together with the Python engine; it lives on in the
history at the commit that ran it, which is the point.

The format and the hash chain are specified in `crates/ttr-tools/src/corpus.rs`. The
continuous/discrete field lists are duplicated here on purpose: the classification decides
which half of the observation digest a slot feeds, and this script must not import it from
the implementation it is checking.
"""

