class Board(NamedTuple):
    name: str
    source: dict  # the layout TOML
    style: Style
    lcc: Lcc
    fit: Fit
    width: float
    height: float
    cities: dict[str, Point]  # board units, nudged


def load_board(name: str, usa_cities: dict) -> Board:
    src = tomllib.loads((LAYOUT_DIR / f"{name}.toml").read_text(encoding="utf-8"))
    assert src["map"] == name, f"{name}.toml: map = {src['map']!r}"
    lcc = Lcc.make(*src["projection"]["center"], *src["projection"]["parallels"])
    cols, rows = src["squares"]
    assert 2 * (cols + rows) - 4 == TRACK_SQUARES, (
        f"{name}: a {cols}x{rows} frame is not {TRACK_SQUARES} squares"
    )
    width, height = cols * SQUARE, rows * SQUARE
    top, right, bottom, left = src["margin"]
    at = {city: spec.get("at") or usa_cities[city]["at"] for city, spec in src["cities"].items()}
    fit = Fit.into(
        (lcc(*v) for v in at.values()),
        Rect(SQUARE + left, SQUARE + top, width - SQUARE - right, height - SQUARE - bottom),
    )
    cities = {}
    for city, spec in src["cities"].items():
        x, y = fit(lcc(*at[city]))
        nx, ny = spec.get("nudge", (0.0, 0.0))
        cities[city] = (x + nx, y + ny)
    return Board(
        name,
        src,
        Style().scaled(src.get("drawing", 1.0), src.get("lettering", src.get("drawing", 1.0))),
        lcc,
        fit,
        width,
        height,
        cities,
    )


def score_track(board: Board) -> list[list[float]]:
    """The 100 squares' top-left corners, clockwise from the top-left corner."""
    cols, rows = board.source["squares"]
    out = [[i * SQUARE, 0.0] for i in range(cols)]
    out += [[board.width - SQUARE, i * SQUARE] for i in range(1, rows)]
    out += [[(cols - 1 - i) * SQUARE, board.height - SQUARE] for i in range(1, cols)]
    return out + [[0.0, (rows - 1 - i) * SQUARE] for i in range(1, rows - 1)]


def lay_routes(board: Board, segments: list) -> tuple[list[dict], list[str]]:
    """Every segment's car spaces, in the map TOML's order, and the tracks without room."""
    st = board.style
    bends = {frozenset((a, b)): (a, bend) for a, b, bend in board.source["routes"]["bends"]}
    pairs: dict[frozenset[str], list[int]] = {}
    for i, (a, b, _, _) in enumerate(segments):
        pairs.setdefault(frozenset((a, b)), []).append(i)
    stray = [sorted(k) for k in set(bends) - set(pairs)]
    assert not stray, f"{board.name}: bends for routes that do not exist: {stray}"

    arcs: dict[frozenset[str], tuple[str, str, Arc, float]] = {}
    for key, idxs in pairs.items():
        a, b, n, _ = segments[idxs[0]]
        assert len(idxs) <= TRACKS_PER_DOUBLE and all(segments[i][2] == n for i in idxs), (
            f"{a}-{b}: not one or two equal tracks"
        )
        start, bend = bends.get(key, (a, 0.0))
        sep = (st.car_width + st.track_gap) / 2 if len(idxs) == TRACKS_PER_DOUBLE else 0.0
        arcs[key] = (
            a,
            b,
            Arc(board.cities[a], board.cities[b], bend if start == a else -bend),
            sep,
        )

    # Where a city's routes leave it close together, each starts far enough out to clear its
    # neighbours; otherwise just clear of the dot.
    leaving: dict[str, list[tuple[frozenset[str], float, float]]] = {}
    for key, (a, b, arc, sep) in arcs.items():
        half = sep + st.car_width / 2 + st.car_clear / 2
        leaving.setdefault(a, []).append((key, arc.leaving(0), half))
        leaving.setdefault(b, []).append((key, arc.leaving(1), half))
    trims: dict[tuple[frozenset[str], str], float] = {}
    for city, routes in leaving.items():
        for key, phi, half in routes:
            inner = max(0.0, half - st.car_width - st.car_clear / 2)
            need = math.sqrt(max(0.0, (st.city_r + st.city_clear) ** 2 - inner**2))
            for other, psi, other_half in routes:
                if other != key:
                    theta = abs((psi - phi + math.pi) % (2 * math.pi) - math.pi)
                    need = max(need, clearance(theta, half, other_half))
            trims[key, city] = need

    out: list[dict] = [{} for _ in segments]
    problems = []
    for key, idxs in pairs.items():
        a, b, arc, sep = arcs[key]
        n = segments[idxs[0]][2]
        t0, t1 = trims[key, a], trims[key, b]
        span = arc.length - t0 - t1
        offsets = (sep, -sep)[: len(idxs)]
        slot = span / n * min(arc.stretch(off) for off in offsets)
        length = min(st.car_max, slot - st.car_gap)
        if length < st.car_min:
            problems.append(
                f"tight: {a}-{b} has {slot:.1f} per car, needs {st.car_min + st.car_gap:.1f}"
            )
        for i, off in zip(idxs, offsets, strict=True):
            cars = [arc.at(t0 + span * (k + 0.5) / n, off) for k in range(n)]
            out[i] = {
                "cities": segments[i][:2],
                "color": segments[i][3],
                "length": fmt(max(length, st.car_min)),
                "cars": [[fmt(x), fmt(y), fmt(norm_deg(math.degrees(d)))] for x, y, d in cars],
            }
    return out, problems


def place_labels(board: Board) -> dict[str, list[float]]:
    """Each plaque's anchor and alignment."""
    out = {}
    for city, spec in board.source["cities"].items():
        side, (tx, ty) = (
            (spec["label"], (0.0, 0.0)) if isinstance(spec["label"], str) else spec["label"]
        )
        (ux, uy), (ax, ay) = COMPASS[side]
        x, y = board.cities[city]
        d = board.style.city_r + board.style.label_gap
        out[city] = [fmt(x + ux * d + tx), fmt(y + uy * d + ty), ax, ay]
    return out


def plaque(board: Board, city: str, label: list[float]) -> list[Point]:
    st = board.style
    w = st.label_size * sum(ADVANCE[ch] + LABEL_TRACKING for ch in city) + 2 * st.label_pad_x
    h = st.label_size + 2 * st.label_pad_y
    x0, y0 = label[0] - label[2] * w, label[1] - label[3] * h
    return [(x0, y0), (x0 + w, y0), (x0 + w, y0 + h), (x0, y0 + h)]


def crowding(board: Board, segments: list[dict], labels: dict[str, list[float]]) -> list[str]:
    """Car spaces on each other or on a city; plaques on a car, a city or each other."""
    st = board.style

    def name(i: int) -> str:
        return f"{'-'.join(segments[i]['cities'])} ({segments[i]['color']})"

    class Shape(NamedTuple):
        poly: list[Point]
        centre: Point
        reach: float  # bounds the shape, for a cheap test before the exact one

    def shape(poly: list[Point]) -> Shape:
        c = (sum(p[0] for p in poly) / len(poly), sum(p[1] for p in poly) / len(poly))
        return Shape(poly, c, max(math.dist(c, p) for p in poly))

    def hits(s: Shape, t: Shape) -> bool:
        return math.dist(s.centre, t.centre) <= s.reach + t.reach and overlap(s.poly, t.poly)

    def near(p: Point, s: Shape, r: float) -> bool:
        return math.dist(p, s.centre) <= s.reach + r and distance(p, s.poly) < r

    grow = st.car_clear / 2
    cars = [
        (i, shape(box_corners(x, y, d, seg["length"] + 2 * grow, st.car_width + 2 * grow)))
        for i, seg in enumerate(segments)
        for x, y, d in seg["cars"]
    ]
    problems = set()
    for j, (i, car) in enumerate(cars):
        problems |= {
            f"cars overlap: {name(i)} and {name(k)}"
            for k, other in cars[j + 1 :]
            if k != i and hits(car, other)
        }
        r = st.city_r + st.city_clear - grow
        problems |= {
            f"car on a city: {name(i)} touches {city}"
            for city, p in board.cities.items()
            if near(p, car, r)
        }
    plaques = {city: shape(plaque(board, city, label)) for city, label in labels.items()}
    inside = Rect(SQUARE, SQUARE, board.width - SQUARE, board.height - SQUARE)
    for what, items in (
        ("car", [(name(i), c) for i, c in cars]),
        ("plaque", list(plaques.items())),
    ):
        problems |= {
            f"{what} off the map: {label}"
            for label, s in items
            if any(
                not (inside.x0 <= x <= inside.x1 and inside.y0 <= y <= inside.y1) for x, y in s.poly
            )
        }
    for city, box in plaques.items():
        problems |= {
            f"plaque on a car: {city} covers {name(i)}" for i, car in cars if hits(box, car)
        }
        problems |= {
            f"plaque on a city: {city} covers {o}"
            for o, p in board.cities.items()
            if o != city and near(p, box, st.city_r)
        }
        problems |= {
            f"plaques overlap: {city} and {o}"
            for o, ob in plaques.items()
            if o > city and hits(box, ob)
        }
    return sorted(problems)


def basemap_key(board: Board) -> str:
    inputs = {
        "version": BASEMAP_VERSION,
        "projection": board.source["projection"],
        "fit": [round(v, 9) for v in board.fit],
        "size": [board.width, board.height],
        "files": NE_FILES,
        "simplify": [SIMPLIFY, SIMPLIFY_THUMB, MIN_LAKE_AREA, MAX_RIVER_RANK, PEAK_STEP],
    }
    return hashlib.sha256(json.dumps(inputs, sort_keys=True).encode()).hexdigest()[:16]


def build_basemap(board: Board, cache: Path) -> dict[str, object]:
    # Clip in longitude/latitude first, so nothing near a pole reaches the projection.
    world = Rect(-150.0, 10.0, -45.0, 70.0)
    frame = Rect(SQUARE - 8, SQUARE - 8, board.width - SQUARE + 8, board.height - SQUARE + 8)

    def project(ring: Ring) -> Ring:
        return [board.fit(board.lcc(lat, lon)) for lon, lat in ring]

    def polygons(
        name: str, keep: Callable[[dict], bool] | None = None, min_area: float = 0.0
    ) -> list[Ring]:
        rings = (
            clip_ring([(p[0], p[1]) for p in ring], world)
            for kind, poly in features(fetch(name, cache), keep)
            if kind == "polygon"
            for ring in poly
        )
        clipped = (clip_ring(project(r), frame) for r in rings if len(r) >= MIN_RING)
        return [r for r in clipped if len(r) >= MIN_RING and ring_area(r) >= min_area]

    def lines(name: str, keep: Callable[[dict], bool] | None = None) -> list[Ring]:
        parts = (
            part for kind, ps in features(fetch(name, cache), keep) if kind == "line" for part in ps
        )
        runs = (
            run
            for part in parts
            for geo in clip_line([(p[0], p[1]) for p in part], world)
            for run in clip_line(project(geo), frame)
        )
        return [simplify(r, SIMPLIFY) for r in runs if len(r) >= MIN_LINE]

    land = polygons("ne_50m_land")
    lakes = polygons("ne_50m_lakes", min_area=MIN_LAKE_AREA)
    ranges = polygons("ne_50m_geography_regions_polys", lambda p: p["FEATURECLA"] == "Range/mtn")

    # Mountains are glyphs on a jittered grid inside each range, on land and off the lakes.
    peaks = []
    for gi in range(int(board.width // PEAK_STEP) + 1):
        for gj in range(int(board.height // PEAK_STEP) + 1):
            h = (gi * 73856093 ^ gj * 19349663) & 0xFFFF
            p = (
                (gi + 0.5 + ((h & 0xFF) / 255 - 0.5) * 0.7) * PEAK_STEP,
                (gj + 0.5 + ((h >> 8) / 255 - 0.5) * 0.7) * PEAK_STEP,
            )
            if (
                any(inside_ring(p, r) for r in ranges)
                and any(inside_ring(p, r) for r in land)
                and not any(inside_ring(p, r) for r in lakes)
            ):
                peaks.append([fmt(p[0]), fmt(p[1]), round(0.8 + 0.4 * ((h >> 4) & 0xF) / 15, 2)])

    return {
        "land": svg_path((simplify([*r, r[0]], SIMPLIFY) for r in land), closed=True),
        "lakes": svg_path((simplify([*r, r[0]], SIMPLIFY) for r in lakes), closed=True),
        "rivers": svg_path(
            lines(
                "ne_50m_rivers_lake_centerlines",
                lambda p: (
                    p["featurecla"] in {"River", "Lake Centerline"}
                    and p["scalerank"] <= MAX_RIVER_RANK
                ),
            ),
            closed=False,
        ),
        "borders": svg_path(lines("ne_50m_admin_0_boundary_lines_land"), closed=False),
        "states": svg_path(
            lines(
                "ne_50m_admin_1_states_provinces_lines",
                lambda p: p["ADM0_NAME"] in {"United States of America", "Canada"},
            ),
            closed=False,
        ),
        "peaks": sorted(peaks),
        "thumb": svg_path(
            (
                s
                for r in land
                if ring_area(r) > THUMB_MIN_AREA
                and len(s := simplify([*r, r[0]], SIMPLIFY_THUMB)) > MIN_RING
            ),
            closed=True,
        ),
    }


def content_sha(basemap: dict) -> str:
    body = {k: v for k, v in basemap.items() if k not in {"key", "sha"}}
    return hashlib.sha256(json.dumps(body, sort_keys=True).encode()).hexdigest()[:16]


def emit(doc: dict) -> str:
    """JSON with one record per line, so a nudge diffs as the lines it moved."""

    def dump(v: object) -> str:
        return json.dumps(v, separators=(",", ":"))

    parts = []
    for key, value in doc.items():
        if isinstance(value, list) and value and isinstance(value[0], dict):
            parts.append(f'  "{key}": [\n' + ",\n".join(f"    {dump(v)}" for v in value) + "\n  ]")
        elif isinstance(value, dict) and value:
            parts.append(
                f'  "{key}": {{\n'
                + ",\n".join(f"    {dump(k)}: {dump(v)}" for k, v in value.items())
                + "\n  }"
            )
        else:
            parts.append(f'  "{key}": {dump(value)}')
    return "{\n" + ",\n".join(parts) + "\n}\n"


def build_map(board: Board, cache: Path, current: dict | None) -> tuple[str, list[str]]:
    spec = tomllib.loads((MAPS_DIR / f"{board.name}.toml").read_text(encoding="utf-8"))
    differ = sorted(set(spec["cities"]) ^ set(board.cities))
    assert not differ, f"{board.name}: the layout and the map disagree on {differ}"
    segments, problems = lay_routes(board, spec["segments"])
    labels = place_labels(board)
    problems += crowding(board, segments, labels)

    key = basemap_key(board)
    if current is not None and current["basemap"]["key"] == key:
        basemap = current["basemap"]
    else:
        basemap = {"key": key, **build_basemap(board, cache)}
        basemap["sha"] = content_sha(basemap)

    st = board.style
    doc = {
        "generated": GENERATED.format(src=f"data/layout/{board.name}.toml"),
        "map": board.name,
        "size": [board.width, board.height],
        "square": SQUARE,
        "car_width": fmt(st.car_width),
        "city_radius": fmt(st.city_r),
        "label_size": fmt(st.label_size),
        "label_pad": [fmt(st.label_pad_x), fmt(st.label_pad_y)],
        "label_tracking": LABEL_TRACKING,
        "track": score_track(board),
        "decor": board.source["decor"],
        "cities": [
            {"name": c, "x": fmt(x), "y": fmt(y), "label": labels[c]}
            for c, (x, y) in board.cities.items()
        ],
        "segments": segments,
        "basemap": basemap,
    }
    return emit(doc), problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--check", action="store_true", help="fail if the output is stale or crowded (offline)"
    )
    parser.add_argument(
        "--cache", type=Path, default=DEFAULT_CACHE, help="the Natural Earth download cache"
    )
    args = parser.parse_args(argv)

    layouts = sorted(p.stem for p in LAYOUT_DIR.glob("*.toml"))
    assert layouts == sorted(MAP_ORDER), f"layouts {layouts} != maps {sorted(MAP_ORDER)}"
    usa_cities = tomllib.loads((LAYOUT_DIR / "usa.toml").read_text(encoding="utf-8"))["cities"]

    failed = False
    for name in MAP_ORDER:
        out = LAYOUT_DIR / f"{name}.json"
        text = out.read_text(encoding="utf-8") if out.exists() else None
        current = json.loads(text) if text else None
        board = load_board(name, usa_cities)
        if args.check:
            # Offline: a basemap whose inputs moved, or that was edited, cannot be checked here.
            if current is None or current["basemap"]["key"] != basemap_key(board):
                print(
                    f"{out.name}: the basemap is stale (its projection, fit or frame moved)",
                    file=sys.stderr,
                )
                failed = True
                continue
            if current["basemap"]["sha"] != content_sha(current["basemap"]):
                print(f"{out.name}: the basemap was edited by hand", file=sys.stderr)
                failed = True
        content, problems = build_map(board, args.cache, current)
        for problem in problems:
            print(f"{name}: {problem}", file=sys.stderr)
        failed |= bool(problems)
        if content == text:
            continue
        if args.check:
            print(f"{out.name} is stale", file=sys.stderr)
            failed = True
        else:
            out.write_text(content, encoding="utf-8")
            print(f"wrote {out.relative_to(REPO_ROOT)}")
    if failed:
        print("\nrun: make layout", file=sys.stderr)
        return 1
    if args.check:
        print("board layout is up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
