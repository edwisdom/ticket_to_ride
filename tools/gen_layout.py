def clip_ring(ring: Ring, box: Rect) -> Ring:
    """Sutherland-Hodgman against a box. The edges this adds along the box are harmless: the
    box is wider than the map, and the frame covers them."""
    edges: list[tuple[Callable[[Point], bool], Callable[[Point, Point], Point]]] = [
        (
            lambda p: p[0] >= box.x0,
            lambda p, q: (box.x0, p[1] + (q[1] - p[1]) * (box.x0 - p[0]) / (q[0] - p[0])),
        ),
        (
            lambda p: p[0] <= box.x1,
            lambda p, q: (box.x1, p[1] + (q[1] - p[1]) * (box.x1 - p[0]) / (q[0] - p[0])),
        ),
        (
            lambda p: p[1] >= box.y0,
            lambda p, q: (p[0] + (q[0] - p[0]) * (box.y0 - p[1]) / (q[1] - p[1]), box.y0),
        ),
        (
            lambda p: p[1] <= box.y1,
            lambda p, q: (p[0] + (q[0] - p[0]) * (box.y1 - p[1]) / (q[1] - p[1]), box.y1),
        ),
    ]
    for inside, cut in edges:
        out: Ring = []
        for prev, cur in zip([*ring[-1:], *ring[:-1]], ring, strict=True):
            if inside(cur):
                if not inside(prev):
                    out.append(cut(prev, cur))
                out.append(cur)
            elif inside(prev):
                out.append(cut(prev, cur))
        ring = out
        if not ring:
            break
    return ring


def clip_line(line: Ring, box: Rect) -> list[Ring]:
    """The runs of a polyline inside a box (Liang-Barsky per segment)."""
    runs: list[Ring] = []
    run: Ring = []
    for p, q in itertools.pairwise(line):
        t0, t1 = 0.0, 1.0
        ex, ey = q[0] - p[0], q[1] - p[1]
        for den, num in (
            (-ex, p[0] - box.x0),
            (ex, box.x1 - p[0]),
            (-ey, p[1] - box.y0),
            (ey, box.y1 - p[1]),
        ):
            if den == 0:
                t1 = t1 if num >= 0 else -1.0
            elif den < 0:
                t0 = max(t0, num / den)
            else:
                t1 = min(t1, num / den)
        if t0 > t1:
            if run:
                runs.append(run)
            run = []
            continue
        if not run:
            run = [(p[0] + t0 * ex, p[1] + t0 * ey)]
        run.append((p[0] + t1 * ex, p[1] + t1 * ey))
        if t1 < 1.0:
            runs.append(run)
            run = []
    return [*runs, run] if run else runs


def simplify(pts: Ring, tol: float) -> Ring:
    """Douglas-Peucker; the endpoints always stay."""
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        i, j = stack.pop()
        (ax, ay), (bx, by) = pts[i], pts[j]
        ex, ey = bx - ax, by - ay
        norm = math.hypot(ex, ey)
        best, at = -1.0, -1
        for k in range(i + 1, j):
            px, py = pts[k]
            d = (
                abs(ex * (py - ay) - ey * (px - ax)) / norm
                if norm
                else math.hypot(px - ax, py - ay)
            )
            if d > best:
                best, at = d, k
        if best > tol:
            keep[at] = True
            stack += [(i, at), (at, j)]
    return [p for p, k in zip(pts, keep, strict=True) if k]


def ring_area(ring: Ring) -> float:
    return (
        abs(sum(p[0] * q[1] - q[0] * p[1] for p, q in zip(ring, [*ring[1:], ring[0]], strict=True)))
        / 2
    )


def inside_ring(p: Point, ring: Ring) -> bool:
    hit = False
    for a, b in zip(ring, [*ring[1:], ring[0]], strict=True):
        if (a[1] > p[1]) != (b[1] > p[1]) and a[0] + (p[1] - a[1]) * (b[0] - a[0]) / (
            b[1] - a[1]
        ) > p[0]:
            hit = not hit
    return hit


def svg_path(rings: Iterable[Ring], closed: bool) -> str:
    def num(v: float) -> str:
        return f"{fmt(v):g}"

    return "".join(
        f"M{num(r[0][0])} {num(r[0][1])}L"
        + " ".join(f"{num(x)} {num(y)}" for x, y in r[1:])
        + ("Z" if closed else "")
        for r in rings
    )


def fetch(name: str, cache: Path) -> dict:
    path = cache / f"{name}.geojson"
    if not path.exists():
        cache.mkdir(parents=True, exist_ok=True)
        print(f"downloading {name} into {cache}")
        with urllib.request.urlopen(NE_URL.format(name), timeout=60) as resp:  # a pinned https URL
            path.write_bytes(resp.read())
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != NE_FILES[name]:
        raise SystemExit(f"{path}: sha256 {digest} is not the pinned {NE_FILES[name]}")
    return json.loads(path.read_text(encoding="utf-8"))


def features(doc: dict, keep: Callable[[dict], bool] | None = None) -> Iterator[tuple[str, list]]:
    """(kind, rings or lines) of each kept feature, multi-geometries split."""
    for feature in doc["features"]:
        geom = feature["geometry"]
        if geom is None or (keep is not None and not keep(feature["properties"])):
            continue
        kind, coords = geom["type"], geom["coordinates"]
        if kind == "Polygon":
            yield "polygon", coords
        elif kind == "MultiPolygon":
            yield from (("polygon", poly) for poly in coords)
        elif kind == "LineString":
            yield "line", [coords]
        elif kind == "MultiLineString":
            yield "line", coords


