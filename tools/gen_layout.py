class Lcc(NamedTuple):
    """Lambert conformal conic on the sphere, in earth radii, y pointing down the page."""

    n: float
    f: float
    rho0: float
    lon0: float

    @classmethod
    def make(cls, lat0: float, lon0: float, p1: float, p2: float) -> Lcc:
        def t(deg: float) -> float:
            return math.tan(math.pi / 4 + math.radians(deg) / 2)

        n = math.log(math.cos(math.radians(p1)) / math.cos(math.radians(p2))) / math.log(
            t(p2) / t(p1)
        )
        f = math.cos(math.radians(p1)) * t(p1) ** n / n
        return cls(n, f, f / t(lat0) ** n, lon0)

    def __call__(self, lat: float, lon: float) -> Point:
        rho = self.f / math.tan(math.pi / 4 + math.radians(lat) / 2) ** self.n
        theta = self.n * math.radians(lon - self.lon0)
        return rho * math.sin(theta), rho * math.cos(theta) - self.rho0


class Rect(NamedTuple):
    x0: float
    y0: float
    x1: float
    y1: float


class Fit(NamedTuple):
    """Projected units -> board units: one scale, one translation."""

    scale: float
    dx: float
    dy: float

    @classmethod
    def into(cls, points: Iterable[Point], box: Rect) -> Fit:
        xs, ys = zip(*points, strict=True)
        scale = min(
            (box.x1 - box.x0) / (max(xs) - min(xs)), (box.y1 - box.y0) / (max(ys) - min(ys))
        )
        return cls(
            scale,
            (box.x0 + box.x1 - scale * (min(xs) + max(xs))) / 2,
            (box.y0 + box.y1 - scale * (min(ys) + max(ys))) / 2,
        )

    def __call__(self, p: Point) -> Point:
        return p[0] * self.scale + self.dx, p[1] * self.scale + self.dy


def box_corners(x: float, y: float, deg: float, length: float, width: float) -> list[Point]:
    c, s = math.cos(math.radians(deg)), math.sin(math.radians(deg))
    hl, hw = length / 2, width / 2
    return [
        (x + c * u - s * v, y + s * u + c * v)
        for u, v in ((-hl, -hw), (hl, -hw), (hl, hw), (-hl, hw))
    ]


def overlap(a: Sequence[Point], b: Sequence[Point]) -> bool:
    """Separating-axis test for two convex polygons."""
    for poly in (a, b):
        for p, q in zip(poly, [*poly[1:], poly[0]], strict=True):
            ax, ay = q[1] - p[1], p[0] - q[0]
            pa = [ax * v[0] + ay * v[1] for v in a]
            pb = [ax * v[0] + ay * v[1] for v in b]
            if max(pa) < min(pb) or max(pb) < min(pa):
                return False
    return True


def distance(p: Point, poly: Sequence[Point]) -> float:
    """From a point to a convex polygon (counter-clockwise on the page); zero inside it."""
    inside, best = True, math.inf
    for a, b in zip(poly, [*poly[1:], poly[0]], strict=True):
        ex, ey = b[0] - a[0], b[1] - a[1]
        inside &= ex * (p[1] - a[1]) - ey * (p[0] - a[0]) >= 0
        t = max(0.0, min(1.0, ((p[0] - a[0]) * ex + (p[1] - a[1]) * ey) / (ex * ex + ey * ey)))
        best = min(best, math.dist(p, (a[0] + t * ex, a[1] + t * ey)))
    return 0.0 if inside else best


class Arc:
    """A route's centre line from city `a` to city `b`: the chord, or a circular arc bowed
    off it by `bend` (sagitta / chord, positive to the left of a -> b on the page)."""

    def __init__(self, a: Point, b: Point, bend: float) -> None:
        chord = math.dist(a, b)
        self.a, self.u = a, ((b[0] - a[0]) / chord, (b[1] - a[1]) / chord)
        self.left = (self.u[1], -self.u[0])
        self.h = bend * chord
        if abs(bend) < EPS:
            self.radius, self.length = math.inf, chord
            return
        self.radius = (chord**2 / 4 + self.h**2) / (2 * abs(self.h))
        k = self.h - math.copysign(
            self.radius, self.h
        )  # the centre is across the chord from the bow
        self.c = ((a[0] + b[0]) / 2 + self.left[0] * k, (a[1] + b[1]) / 2 + self.left[1] * k)
        self.alpha = math.atan2(a[1] - self.c[1], a[0] - self.c[0])
        self.sweep = (math.atan2(b[1] - self.c[1], b[0] - self.c[0]) - self.alpha + math.pi) % (
            2 * math.pi
        ) - math.pi
        self.length = self.radius * abs(self.sweep)

    def at(self, s: float, offset: float) -> tuple[float, float, float]:
        """The point `s` along the centre line, moved `offset` to its left, and the heading."""
        if self.radius == math.inf:
            x, y = self.a[0] + self.u[0] * s, self.a[1] + self.u[1] * s
            return (
                x + self.left[0] * offset,
                y + self.left[1] * offset,
                math.atan2(self.u[1], self.u[0]),
            )
        t = self.alpha + math.copysign(s / self.radius, self.sweep)
        r = self.radius + offset * math.copysign(
            1.0, self.h
        )  # bowing left puts the left side outside
        return (
            self.c[0] + r * math.cos(t),
            self.c[1] + r * math.sin(t),
            t + math.copysign(math.pi / 2, self.sweep),
        )

    def stretch(self, offset: float) -> float:
        """How much longer a track `offset` to the left is than the centre line."""
        return (
            1.0
            if self.radius == math.inf
            else 1 + offset * math.copysign(1.0, self.h) / self.radius
        )

    def leaving(self, end: int) -> float:
        """The direction the route leaves city `a` (end 0) or `b` (end 1) in, radians."""
        return self.at(0.0, 0.0)[2] if end == 0 else self.at(self.length, 0.0)[2] + math.pi


def clearance(theta: float, mine: float, theirs: float) -> float:
    """How far from a city a route must start to clear a neighbour leaving it `theta` radians
    away, given both half-widths: the far corner of the two strips' crossing."""
    if theta < EPS:
        return math.inf
    if theta <= math.pi / 2:
        return (mine * math.cos(theta) + theirs) / math.sin(theta)
    return theirs * math.sin(theta)


def norm_deg(deg: float) -> float:
    """A car space is symmetric, so its angle is kept in (-90, 90]."""
    return 90.0 - (90.0 - deg) % 180.0


def fmt(v: float) -> float:
    r = round(v, 1)
    return 0.0 if r == 0 else r


