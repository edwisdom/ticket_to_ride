def emit_toml(spec: Spec, source: str) -> str:
    """Emit a map TOML. Only used for usa.toml, whose source is RULES.md."""

    def name_of_color(c: int) -> str:
        return GRAY_NAME if c == GRAY else spec.color_names[c]

    lines = [
        f"# @generated by tools/gen_board.py from {source} -- DO NOT EDIT BY HAND.",
        "#",
        f"# {source} is the human-readable source of truth for this map. To change the",
        "# board, edit it and re-run `make board`.",
        f"schema = {SCHEMA_VERSION}",
        f'name = "{spec.name}"',
        f"trains_per_player = {spec.trains_per_player}",
        f"min_players = {spec.min_players}",
        f"max_players = {spec.max_players}",
        f"longest_path_bonus = {spec.longest_bonus}",
        "colors = [" + ", ".join(f'"{c}"' for c in spec.color_names) + "]",
        f"cards_per_color = {spec.cards_per_color}",
        f"locomotives = {spec.locomotives}",
        "# route_points[i] scores a route of length i+1.",
        "route_points = [" + ", ".join(str(p) for p in spec.route_points[1:]) + "]",
        f"initial_ticket_deal = {spec.initial_ticket_deal}",
        f"initial_ticket_keep_min = {spec.initial_ticket_keep_min}",
        f"draw_ticket_deal = {spec.draw_ticket_deal}",
        f"draw_ticket_keep_min = {spec.draw_ticket_keep_min}",
        "",
        "# City index order is this list's order, which the generator sorts.",
        "cities = [",
    ]
    lines += [f'  "{c}",' for c in spec.cities]
    lines += [
        "]",
        "",
        '# [from, to, length, color]; "gray" accepts a set of any one color.',
        "segments = [",
    ]
    lines += [
        f'  ["{spec.cities[a]}", "{spec.cities[b]}", {n}, "{name_of_color(c)}"],'
        for a, b, n, c in spec.segments
    ]
    lines += ["]", "", "# [from, to, points]", "tickets = ["]
    lines += [f'  ["{spec.cities[a]}", "{spec.cities[b]}", {p}],' for a, b, p in spec.tickets]
    lines += ["]", ""]
    return "\n".join(lines)


def _py_tuples(rows: tuple[tuple[int, ...], ...], per_line: int) -> list[str]:
    cells = ["(" + ", ".join(str(v) for v in row) + ")," for row in rows]
    return ["        " + " ".join(cells[i : i + per_line]) for i in range(0, len(cells), per_line)]


def emit_python(specs: list[Spec]) -> str:
    lines = [
        f"# {BANNER.splitlines()[0]}",
        f"# {BANNER.splitlines()[1]}",
        '"""Generated board constants.',
        "",
        "Indices, orderings and DATA_HASH are frozen; see docs/CONTRACT.md. Nothing in here",
        "is hand-maintained -- edit RULES.md or ticket_to_ride/data/maps/*.toml instead.",
        '"""',
        "",
        "from types import MappingProxyType",
        "",
        "from ticket_to_ride.data.rawmap import RawMap",
        "",
        f"SCHEMA_VERSION = {SCHEMA_VERSION}",
        "",
    ]
    for spec in specs:
        lines += [
            f"{spec.name.upper()} = RawMap(",
            f'    name="{spec.name}",',
            "    cities=(",
        ]
        lines += [f'        "{c}",' for c in spec.cities]
        lines += ["    ),", "    segments=("]
        lines += _py_tuples(spec.segments, 4)
        lines += ["    ),", "    tickets=("]
        lines += _py_tuples(spec.tickets, 5)
        lines += [
            "    ),",
            "    color_names=(" + "".join(f'"{c}", ' for c in spec.color_names).rstrip() + "),",
            f"    trains_per_player={spec.trains_per_player},",
            f"    cards_per_color={spec.cards_per_color},",
            f"    locomotives={spec.locomotives},",
            "    route_points=(" + ", ".join(str(p) for p in spec.route_points) + "),",
            f"    longest_bonus={spec.longest_bonus},",
            f"    initial_ticket_deal={spec.initial_ticket_deal},",
            f"    initial_ticket_keep_min={spec.initial_ticket_keep_min},",
            f"    draw_ticket_deal={spec.draw_ticket_deal},",
            f"    draw_ticket_keep_min={spec.draw_ticket_keep_min},",
            f"    min_players={spec.min_players},",
            f"    max_players={spec.max_players},",
            f'    data_hash="{data_hash(spec)}",',
            ")",
            "",
        ]
    entries = ", ".join(f'"{s.name}": {s.name.upper()}' for s in specs)
    lines += [f"MAPS = MappingProxyType({{{entries}}})", ""]
    return "\n".join(lines)


def _rs_tuples(rows: tuple[tuple[int, ...], ...], per_line: int) -> list[str]:
    cells = ["(" + ", ".join(str(v) for v in row) + ")," for row in rows]
    return ["    " + " ".join(cells[i : i + per_line]) for i in range(0, len(cells), per_line)]


def emit_rust(specs: list[Spec]) -> str:
    lines = [
        f"// {BANNER.splitlines()[0]}",
        f"// {BANNER.splitlines()[1]}",
        "//!",
        "//! Generated board constants, the Rust half of the pair emitted by",
        "//! `tools/gen_board.py`. The Python half is `ticket_to_ride/data/board_gen.py`;",
        "//! the two are emitted from one canonicalized spec so the engines cannot disagree",
        "//! about the board itself. Indices and DATA_HASH are frozen -- see docs/CONTRACT.md.",
        "",
        "#![allow(dead_code)]",
        "",
        f"pub const SCHEMA_VERSION: u32 = {SCHEMA_VERSION};",
        "",
        "/// One board's data. Mirrors `ticket_to_ride.data.rawmap.RawMap` field for field.",
        "pub struct RawMap {",
        "    pub name: &'static str,",
        "    pub cities: &'static [&'static str],",
        "    /// (city_a, city_b, length, color); color 255 = gray.",
        "    pub segments: &'static [(u8, u8, u8, u8)],",
        "    /// (city_a, city_b, points)",
        "    pub tickets: &'static [(u8, u8, u8)],",
        "    pub color_names: &'static [&'static str],",
        "    pub trains_per_player: u8,",
        "    pub cards_per_color: u8,",
        "    pub locomotives: u8,",
        "    /// Indexed by route length; index 0 is unused.",
        "    pub route_points: &'static [u8],",
        "    pub longest_bonus: u8,",
        "    pub initial_ticket_deal: u8,",
        "    pub initial_ticket_keep_min: u8,",
        "    pub draw_ticket_deal: u8,",
        "    pub draw_ticket_keep_min: u8,",
        "    pub min_players: u8,",
        "    pub max_players: u8,",
        "    pub data_hash: &'static str,",
        "}",
        "",
        "impl RawMap {",
        "    #[inline]",
        "    pub const fn locomotive(&self) -> u8 {",
        "        self.color_names.len() as u8",
        "    }",
        "",
        "    #[inline]",
        "    pub const fn n_card_types(&self) -> usize {",
        "        self.color_names.len() + 1",
        "    }",
        "}",
        "",
    ]
    for spec in specs:
        up = spec.name.upper()
        lines += [
            f"pub const {up}_CITIES: [&str; {len(spec.cities)}] = [",
            "    " + " ".join(f'"{c}",' for c in spec.cities),
            "];",
            "",
            f"pub const {up}_SEGMENTS: [(u8, u8, u8, u8); {len(spec.segments)}] = [",
        ]
        lines += _rs_tuples(spec.segments, 4)
        lines += [
            "];",
            "",
            f"pub const {up}_TICKETS: [(u8, u8, u8); {len(spec.tickets)}] = [",
        ]
        lines += _rs_tuples(spec.tickets, 5)
        lines += [
            "];",
            "",
            f"pub const {up}_COLOR_NAMES: [&str; {len(spec.color_names)}] = ["
            + " ".join(f'"{c}",' for c in spec.color_names)
            + "];",
            "",
            f"pub const {up}: RawMap = RawMap {{",
            f'    name: "{spec.name}",',
            f"    cities: &{up}_CITIES,",
            f"    segments: &{up}_SEGMENTS,",
            f"    tickets: &{up}_TICKETS,",
            f"    color_names: &{up}_COLOR_NAMES,",
            f"    trains_per_player: {spec.trains_per_player},",
            f"    cards_per_color: {spec.cards_per_color},",
            f"    locomotives: {spec.locomotives},",
            "    route_points: &[" + ", ".join(str(p) for p in spec.route_points) + "],",
            f"    longest_bonus: {spec.longest_bonus},",
            f"    initial_ticket_deal: {spec.initial_ticket_deal},",
            f"    initial_ticket_keep_min: {spec.initial_ticket_keep_min},",
            f"    draw_ticket_deal: {spec.draw_ticket_deal},",
            f"    draw_ticket_keep_min: {spec.draw_ticket_keep_min},",
            f"    min_players: {spec.min_players},",
            f"    max_players: {spec.max_players},",
            f'    data_hash: "{data_hash(spec)}",',
            "};",
            "",
        ]
    refs = ", ".join(f"&{s.name.upper()}" for s in specs)
    lines += [f"pub const MAPS: [&RawMap; {len(specs)}] = [{refs}];", ""]
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Driver
# ---------------------------------------------------------------------------


def build() -> dict[Path, str]:
    """Produce every generated file's intended content, keyed by path."""
    rules_md = RULES_MD.read_text(encoding="utf-8")
    usa = to_spec(parse_rules_md(rules_md))
    validate(usa)
    check_usa_against_rules(usa, rules_md)

    usa_toml = emit_toml(usa, "RULES.md")
    # The TOML emitter has to be lossless, or usa.toml quietly stops describing the board
    # the generated constants were built from.
    assert to_spec(tomllib.loads(usa_toml)) == usa, "usa.toml does not round-trip"
    out = {MAPS_DIR / "usa.toml": usa_toml}

    specs = {"usa": usa}
    for path in sorted(MAPS_DIR.glob("*.toml")):
        if path.stem == "usa":
            continue
        spec = to_spec(tomllib.loads(path.read_text(encoding="utf-8")))
        assert spec.name == path.stem, f"{path.name}: name={spec.name!r} does not match filename"
        validate(spec)
        specs[spec.name] = spec

    assert set(specs) == set(MAP_ORDER), f"maps {sorted(specs)} != expected {sorted(MAP_ORDER)}"
    ordered = [specs[n] for n in MAP_ORDER]

    # usa.toml is itself generated, so a stale one must not silently feed the emitters.
    # Everything downstream is built from `usa` parsed straight out of RULES.md.
    out[OUT_PY] = emit_python(ordered)
    out[OUT_RS] = emit_rust(ordered)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args(argv)

    stale: list[Path] = []
    for path, content in build().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO_ROOT)}")

    if stale:
        names = "\n  ".join(str(p.relative_to(REPO_ROOT)) for p in stale)
        print(f"stale generated files:\n  {names}\n\nrun: make board", file=sys.stderr)
        return 1
    if args.check:
        print("board data is up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
