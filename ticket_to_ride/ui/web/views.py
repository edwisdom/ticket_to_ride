def scores(state: ttr_rust.State) -> list[p.Score]:
    ranks = state.ranks()
    return [
        p.Score(
            seat=seat,
            routes=routes,
            tickets_made=made,
            tickets_missed=missed,
            ticket_points=ticket_points,
            longest_bonus=bonus,
            longest_trail=trail,
            total=total,
            rank=ranks[seat],
        )
        for seat, (routes, made, missed, ticket_points, bonus, trail, _, total) in enumerate(
            state.score_breakdown()
        )
    ]


def explanation(
    game: ttr_rust.Game, before: ttr_rust.State, e: ttr_rust.Explanation, agent: str
) -> p.Explanation:
    """A bot's reasoning, its candidates decoded as the bot saw them."""
    return p.Explanation(
        agent=agent,
        tier=e.tier,
        chosen=e.chosen,
        rule=e.rule,
        context=[p.Term(name=name, value=value) for name, value in e.context],
        candidates=[
            p.Candidate(
                action=decode(game, before, c.action, viewer=before.current_player()),
                total=c.total if math.isfinite(c.total) else None,
                rule=c.rule,
                terms=[p.Term(name=name, value=value) for name, value in c.terms],
                facts=[p.Term(name=name, value=value) for name, value in c.facts],
            )
            for c in e.candidates
        ],
    )
