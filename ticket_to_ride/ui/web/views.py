"""From engine state to protocol: views, decoded actions, the log, explanations.

**This is where hidden information is kept from the browser** (PLAN.md §14.2). A seat view
is a function of the position and the seat, built only from what that seat can know: the
public board and counters, its own hand, tickets and offer, opponents' publicly known
cards, and the bot-parity assistance (unseen counts per colour, ticket progress). The
masking test holds it to that exactly: a seat's view of a position equals its view of any
`resample_from_infoset(seat)` of it, which differs in everything the seat cannot see.

The server implements no rules here either. Legality, payments, ticket progress and action
layout all come from the engine; this module only reads and names them.
"""

from __future__ import annotations

import json
import math
from dataclasses import dataclass
from functools import cache
from pathlib import Path

import ttr_rust

from ticket_to_ride.ui.web import protocol as p

#: `seg_owner` sentinels (crates/ttr-core/src/config.rs).
FREE = 255
CLOSED = 254
#: `final_left` before the end is triggered.
NOT_TRIGGERED = 255

#: The client's drawing of each board, generated by tools/gen_layout.py (PLAN.md §14.2).
LAYOUT_DIR = Path(__file__).resolve().parents[2] / "data" / "layout"

KEEP_PHASES = ("INITIAL_TICKETS", "TICKET_KEEP")

#: Between a route's or a ticket's two cities.
DASH = " \u2013 "

#: The engine's phase names, as the protocol spells them.
PHASES: dict[str, p.Phase] = {
    "INITIAL_TICKETS": "initial_tickets",
    "MAIN": "main",
    "DRAW_SECOND": "draw_second",
    "TICKET_KEEP": "ticket_keep",
    "TERMINAL": "terminal",
}


@dataclass(frozen=True)
class BoardInfo:
    """A map's engine data, read once, with the names plain-English text needs."""

    name: str
    cities: list[str]
    segments: list[tuple[int, int, int, int | None, int | None]]
    tickets: list[tuple[int, int, int]]
    colors: list[str]
    locomotive: int
    raw: dict

    def card(self, card_type: int) -> str:
        return "locomotive" if card_type == self.locomotive else self.colors[card_type]

    def a_card(self, card_type: int) -> str:
        """`a red`, `an orange`: the article follows the colour's spelling."""
        name = self.card(card_type)
        return f"{'an' if name[0] in 'aeiou' else 'a'} {name}"

    def cards(self, card_type: int, count: int) -> str:
        name = self.card(card_type)
        return f"{count} {name}{'s' if count != 1 and name == 'locomotive' else ''}"

    def route(self, segment: int) -> str:
        a, b, length, color, _ = self.segments[segment]
        shade = "gray" if color is None else self.colors[color]
        return f"{self.cities[a]}{DASH}{self.cities[b]} ({length} {shade})"

    def ticket(self, ticket: int) -> str:
        a, b, points = self.tickets[ticket]
        return f"{self.cities[a]}{DASH}{self.cities[b]} ({points})"


@cache
def board_info(map_name: str) -> BoardInfo:
    raw = ttr_rust.board_data(map_name)
    return BoardInfo(
        name=raw["name"],
        cities=list(raw["cities"]),
        segments=[tuple(s) for s in raw["segments"]],
        tickets=[tuple(t) for t in raw["tickets"]],
        colors=list(raw["colors"]),
        locomotive=int(raw["locomotive"]),
        raw=raw,
    )


def board(map_name: p.MapName) -> p.Board:
    """`GET /api/boards/{map}`: the engine's arrays plus the client's layout, if built."""
    info = board_info(map_name)
    raw = info.raw
    path = LAYOUT_DIR / f"{map_name}.json"
    layout = json.loads(path.read_text(encoding="utf-8")) if path.exists() else None
    return p.Board(
        name=map_name,
        data_hash=raw["data_hash"],
        cities=info.cities,
        segments=[
            p.Segment(id=i, a=a, b=b, length=length, color=color, sibling=sibling)
            for i, (a, b, length, color, sibling) in enumerate(info.segments)
        ],
        tickets=[
            p.Ticket(id=i, a=a, b=b, points=points) for i, (a, b, points) in enumerate(info.tickets)
        ],
        colors=info.colors,
        locomotive=info.locomotive,
        card_counts=list(raw["card_counts"]),
        trains_per_player=raw["trains_per_player"],
        end_trigger_trains=raw["end_trigger_trains"],
        route_points=list(raw["route_points"]),
        longest_bonus=raw["longest_bonus"],
        players=list(raw["players"]),
        initial_ticket_deal=raw["initial_ticket_deal"],
        initial_ticket_keep_min=raw["initial_ticket_keep_min"],
        draw_ticket_deal=raw["draw_ticket_deal"],
        draw_ticket_keep_min=raw["draw_ticket_keep_min"],
        faceup_slots=raw["faceup_slots"],
        action_space=raw["action_space"],
        layout=layout,
    )


# ---------------------------------------------------------------------------
# Views
# ---------------------------------------------------------------------------


def _sees(viewer: int | None, seat: int) -> bool:
    """`viewer` None is omniscient."""
    return viewer is None or viewer == seat


def view(state: ttr_rust.State, viewer: int | None) -> p.View:
    """The position as `viewer` may see it; `None` sees everything."""
    n = len(state.trains)
    owners = state.seg_owner
    trails = state.longest_trails()
    keeping = state.phase_name in KEEP_PHASES
    seats = []
    for seat in range(n):
        hand = state.hand_of(seat)
        shown = _sees(viewer, seat)
        seats.append(
            p.SeatView(
                seat=seat,
                trains=state.trains[seat],
                score=state.score[seat],
                hand_size=sum(hand),
                known=list(state.certain_of(seat)),
                ticket_count=len(state.tickets_of(seat)),
                longest_trail=trails[seat],
                hand=list(hand) if shown else None,
                tickets=_progress(state, seat) if shown else None,
            )
        )
    return p.View(
        viewer=viewer,
        ply=len(state.history()),
        turn=state.turn,
        phase=PHASES[state.phase_name],
        current=state.current_player(),
        draws_left=state.draws_left,
        final_turns=None if state.final_left == NOT_TRIGGERED else state.final_left,
        owners=[owner if owner < n else None for owner in owners],
        closed=[segment for segment, owner in enumerate(owners) if owner == CLOSED],
        faceup=[card if card >= 0 else None for card in state.faceup],
        deck=sum(state.deck_counts()),
        discard=state.discard(),
        ticket_deck=state.tickets_remaining,
        seats=seats,
        offer=state.offer() if keeping and _sees(viewer, state.current_player()) else None,
        unseen=state.unseen_counts(viewer) if viewer is not None else None,
        deck_cards=list(state.deck_counts()) if viewer is None else None,
    )


def _progress(state: ttr_rust.State, seat: int) -> list[p.TicketProgress]:
    return [
        p.TicketProgress(ticket=ticket, connected=connected, remaining=remaining)
        for ticket, connected, remaining in state.ticket_progress(seat)
    ]


