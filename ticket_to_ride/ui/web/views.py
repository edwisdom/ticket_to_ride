# Actions
# ---------------------------------------------------------------------------


def decode(
    game: ttr_rust.Game,
    before: ttr_rust.State,
    action: int,
    *,
    viewer: int | None,
    after: ttr_rust.State | None = None,
) -> p.Action:
    """`action`, played by `before.current_player()`, as `viewer` may see it.

    Without `after` it is an option still to be taken (a legal action, a bot's candidate);
    with it, a move made, so a blind draw's card and the tickets dealt are known -- to the
    actor (and an omniscient viewer) only.
    """
    info = board_info(game.map_name)
    actor = before.current_player()
    shown = _sees(viewer, actor)
    decoded = game.decode_action(action)
    match decoded.kind:
        case "claim":
            assert decoded.segment is not None and decoded.pay is not None
            colored, locomotives = before.claim_payment(action)
            claim = p.ClaimAction(
                kind="claim",
                id=action,
                segment=decoded.segment,
                color=decoded.pay,
                colored=colored,
                locomotives=locomotives,
                label="",
            )
            label = f"Claim {info.route(claim.segment)} with {payment(info, claim)}"
            return claim.model_copy(update={"label": label})
        case "draw":
            if decoded.blind:
                card = _drawn(before, after, actor) if shown and after is not None else None
                return p.DrawAction(
                    kind="draw", id=action, slot=None, card=card, label="Draw from the deck"
                )
            assert decoded.slot is not None
            card = before.faceup[decoded.slot]
            return p.DrawAction(
                kind="draw",
                id=action,
                slot=decoded.slot,
                card=card,
                label=f"Take the face-up {info.card(card)}",
            )
        case "draw_tickets":
            dealt, tickets = (None, None) if after is None else _dealt(before, after, actor)
            return p.DrawTicketsAction(
                kind="draw_tickets",
                id=action,
                dealt=dealt,
                tickets=tickets if shown else None,
                label="Draw destination tickets",
            )
        case "keep":
            offer = before.offer()
            kept = [offer[i] for i in decoded.offer_indices]
            returned = [t for i, t in enumerate(offer) if i not in decoded.offer_indices]
            label = (
                "Keep " + " and ".join(info.ticket(t) for t in kept)
                if shown
                else f"Keep {len(kept)} ticket{'s' if len(kept) != 1 else ''}"
            )
            return p.KeepAction(
                kind="keep",
                id=action,
                offer_indices=list(decoded.offer_indices),
                count=len(kept),
                tickets=kept if shown else None,
                returned=returned if shown else None,
                label=label,
            )
        case _:
            return p.PassAction(kind="pass", id=action, label="Pass")


def payment(info: BoardInfo, claim: p.ClaimAction) -> str:
    """`3 blue + 1 locomotive`."""
    return " + ".join(
        info.cards(card, count)
        for card, count in ((claim.color, claim.colored), (info.locomotive, claim.locomotives))
        if count
    )


def _drawn(before: ttr_rust.State, after: ttr_rust.State, seat: int) -> int:
    """The card a blind draw added to `seat`'s hand."""
    gained = [b - a for a, b in zip(before.hand_of(seat), after.hand_of(seat), strict=True)]
    return gained.index(1)


def _dealt(before: ttr_rust.State, after: ttr_rust.State, seat: int) -> tuple[int, list[int]]:
    """The tickets a draw dealt: the offer now open, or -- when the deck held a single
    ticket and the engine kept it for the seat -- the ticket it gained."""
    if after.phase_name == "TICKET_KEEP" and after.current_player() == seat:
        offer = after.offer()
        return len(offer), offer
    gained = sorted(set(after.tickets_of(seat)) - set(before.tickets_of(seat)))
    return len(gained), gained


def legal(game: ttr_rust.Game, state: ttr_rust.State, viewer: int | None) -> list[p.Action]:
    """The viewer's options, decoded -- empty unless the viewer is a seat and to move."""
    if viewer is None or state.is_terminal() or state.current_player() != viewer:
        return []
    return [decode(game, state, action, viewer=viewer) for action in state.legal_actions()]


def entry(
    game: ttr_rust.Game,
    before: ttr_rust.State,
    action: int,
    after: ttr_rust.State,
    *,
    viewer: int | None,
    names: list[str],
) -> p.LogEntry:
    """One move, in plain English, as `viewer` may see it."""
    info = board_info(game.map_name)
    seat = before.current_player()
    decoded = decode(game, before, action, viewer=viewer, after=after)
    who = "You" if viewer == seat else names[seat]
    text = f"{who} {_said(info, decoded, before, after)}."
    if before.final_left == NOT_TRIGGERED and after.final_left != NOT_TRIGGERED:
        # Train pieces, not "trains": a player read "down to 0 trains" as the cards in hand.
        # And "no", not "0", which the client's old-style figures draw as a small o.
        left = after.trains[seat]
        pieces = "no train pieces" if left == 0 else f"{left} train piece{'s' if left != 1 else ''}"
        text += f" {who} {'have' if who == 'You' else 'has'} {pieces} left: "
        text += "everyone gets one more turn."
    if after.is_terminal():
        text += " Game over."
    return p.LogEntry(ply=len(before.history()), seat=seat, action=decoded, text=text)


def _said(info: BoardInfo, decoded: p.Action, before: ttr_rust.State, after: ttr_rust.State) -> str:
    """What a move did, after its actor's name."""
    match decoded:
        case p.ClaimAction():
            said = f"claimed {info.route(decoded.segment)} with {payment(info, decoded)}"
        case p.DrawAction(slot=None, card=card):
            said = f"drew {'a card' if card is None else info.a_card(card)} from the deck"
        case p.DrawAction(card=int(card)):
            said = f"took the face-up {info.card(card)}"
        case p.DrawTicketsAction(dealt=dealt, tickets=tickets):
            said = f"drew {dealt} destination ticket{'s' if dealt != 1 else ''}"
            if after.phase_name != "TICKET_KEEP" and dealt == 1:
                said += " and kept it"
            if tickets:
                said += ": " + ", ".join(info.ticket(t) for t in tickets)
        case p.KeepAction(tickets=tickets, count=count):
            opening = "opening " if before.phase_name == "INITIAL_TICKETS" else ""
            if tickets is None:
                said = f"kept {count} {opening}ticket{'s' if count != 1 else ''}"
            else:
                said = f"kept {opening}tickets " + ", ".join(info.ticket(t) for t in tickets)
        case _:
            said = "passed: there was no legal move"
    return said


