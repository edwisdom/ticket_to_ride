"""The play store: every game the web server has hosted, at `runs/play.db`.

**The source of truth; the server's memory is a cache over it** (PLAN.md §14.2). Each
decision is appended as it is made, and a game is rebuilt from `(seed, actions)`. Replays
and supervision data are these rows replayed: nothing the engine can recompute is stored.

A database of its own, apart from the arena's `results.db`, because it is the web app's
operational store -- the one that becomes Postgres when the site goes public. So the SQL
stays portable and all of it lives in this module: ids generated by the application as
TEXT (no autoincrement, no rowid), flags as INTEGER, timestamps as ISO-8601 UTC TEXT,
seeds as BIGINT below 2^63 (both databases' integers are signed 64-bit, the trap GOTCHAS
records for state hashes), and `ON CONFLICT ... DO NOTHING`. Moving to Postgres changes the
driver and its `?` placeholders, not the statements.
"""

from __future__ import annotations

import datetime as dt
import hashlib
import secrets
import sqlite3
import threading
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

from ticket_to_ride.eval.store import AgentRow

#: Bumped when the schema changes in a way an older database cannot be read as.
SCHEMA_VERSION = 1

SCHEMA = """
CREATE TABLE IF NOT EXISTS meta (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- People, and bots as rows pointing at their agent identity -- the results store's key --
-- so a bot is one player across every game it sits in. A person's auth provider and
-- external id arrive with accounts.
CREATE TABLE IF NOT EXISTS player (
    player_id      TEXT PRIMARY KEY,
    kind           TEXT NOT NULL CHECK (kind IN ('human', 'bot')),
    name           TEXT NOT NULL,
    auth_provider  TEXT,
    external_id    TEXT,
    spec           TEXT,
    family         TEXT,
    params_hash    TEXT,
    behaviour_hash TEXT,
    checkpoint     TEXT,
    created_utc    TEXT NOT NULL
);

-- The seed is served only once the game is over. The versions and hashes say which
-- engine, rules and board it was played under, so a rebuild under different ones is
-- refused instead of replaying a different game.
CREATE TABLE IF NOT EXISTS game (
    game_id          TEXT PRIMARY KEY,
    map_name         TEXT NOT NULL,
    n_players        INTEGER NOT NULL,
    mode             TEXT NOT NULL CHECK (mode IN ('play', 'spectate')),
    rated            INTEGER NOT NULL,
    assist           TEXT NOT NULL,
    status           TEXT NOT NULL CHECK (status IN ('active', 'finished')),
    seed             BIGINT NOT NULL,
    contract_version INTEGER NOT NULL,
    obs_version      INTEGER NOT NULL,
    data_hash        TEXT NOT NULL,
    rules_hash       TEXT NOT NULL,
    git_sha          TEXT,
    client_build     TEXT,
    created_utc      TEXT NOT NULL,
    finished_utc     TEXT,
    final_hash       TEXT
);

-- Final scores, their breakdown and the rank are NULL until the game ends.
CREATE TABLE IF NOT EXISTS seat (
    game_id        TEXT NOT NULL REFERENCES game(game_id),
    seat           INTEGER NOT NULL,
    player_id      TEXT NOT NULL REFERENCES player(player_id),
    score          INTEGER,
    routes         INTEGER,
    tickets_made   INTEGER,
    tickets_missed INTEGER,
    ticket_points  INTEGER,
    longest_bonus  INTEGER,
    longest_trail  INTEGER,
    rank           INTEGER,
    PRIMARY KEY (game_id, seat)
);

-- One row per decision. The primary key is what makes a move impossible to record twice.
CREATE TABLE IF NOT EXISTS action (
    game_id    TEXT NOT NULL REFERENCES game(game_id),
    ply        INTEGER NOT NULL,
    seat       INTEGER NOT NULL,
    action     INTEGER NOT NULL,
    server_utc TEXT NOT NULL,
    think_ms   INTEGER NOT NULL,
    PRIMARY KEY (game_id, ply)
);

CREATE INDEX IF NOT EXISTS seat_by_player ON seat(player_id);
CREATE INDEX IF NOT EXISTS game_by_status ON game(status, map_name);
"""


def now() -> str:
    return dt.datetime.now(dt.UTC).isoformat(timespec="milliseconds")


def bot_id(identity: AgentRow) -> str:
    """A bot's player id, from what it plays: the same bot is the same player in every
    store, and a retuned one is a new player."""
    key = "|".join(str(part) for part in identity.key)
    return "bot-" + hashlib.blake2b(key.encode(), digest_size=8).hexdigest()


@dataclass(frozen=True)
class PlayerRow:
    player_id: str
    kind: Literal["human", "bot"]
    name: str
    spec: str | None
    family: str | None
    params_hash: str | None
    behaviour_hash: str | None
    checkpoint: str | None
    created_utc: str

    @property
    def identity(self) -> AgentRow | None:
        """A bot's agent identity; `None` for a person."""
        if self.kind != "bot":
            return None
        assert self.spec and self.family and self.params_hash and self.behaviour_hash
        return AgentRow(
            spec=self.spec,
            family=self.family,
            params_hash=self.params_hash,
            behaviour_hash=self.behaviour_hash,
            checkpoint=self.checkpoint,
        )


@dataclass(frozen=True)
class GameRow:
    game_id: str
    map_name: Literal["usa", "mini"]
    n_players: int
    mode: Literal["play", "spectate"]
    rated: bool
    assist: str
    status: Literal["active", "finished"]
    seed: int
    contract_version: int
    obs_version: int
    data_hash: str
    rules_hash: str
    git_sha: str | None
    client_build: str | None
    created_utc: str
    finished_utc: str | None = None
    final_hash: str | None = None


@dataclass(frozen=True)
class SeatRow:
    game_id: str
    seat: int
    player_id: str
    score: int | None
    routes: int | None
    tickets_made: int | None
    tickets_missed: int | None
    ticket_points: int | None
    longest_bonus: int | None
    longest_trail: int | None
    rank: int | None


@dataclass(frozen=True)
class ActionRow:
    ply: int
    seat: int
    action: int
    server_utc: str
    think_ms: int


@dataclass(frozen=True)
class FinalSeat:
    """One seat's result, written with a game's last action."""

    seat: int
    score: int
    routes: int
    tickets_made: int
    tickets_missed: int
    ticket_points: int
    longest_bonus: int
    longest_trail: int
    rank: int


_GAME_COLUMNS = (
    "game_id, map_name, n_players, mode, rated, assist, status, seed, contract_version,"
    " obs_version, data_hash, rules_hash, git_sha, client_build, created_utc, finished_utc,"
    " final_hash"
)
_PLAYER_COLUMNS = (
    "player_id, kind, name, spec, family, params_hash, behaviour_hash, checkpoint, created_utc"
)


class PlayStore:
    """The play database. One connection, shared across the server's threads under a lock;
    every write is one transaction."""

    def __init__(self, path: str | Path) -> None:
        self.path = Path(path)
        if self.path.parent != Path():
            self.path.parent.mkdir(parents=True, exist_ok=True)
        self._lock = threading.RLock()
        self.db = sqlite3.connect(self.path, isolation_level=None, check_same_thread=False)
        self.db.row_factory = sqlite3.Row
        try:
            # WAL: a reader -- a rating refit, a review -- never blocks the move being
            # recorded, and a crash leaves the last committed move intact.
            self.db.execute("PRAGMA journal_mode=WAL")
            self.db.execute("PRAGMA synchronous=NORMAL")
            self.db.execute("PRAGMA foreign_keys=ON")
            self.db.executescript(SCHEMA)
            self._check_version()
        except Exception:
            # Closed before propagating, for the reason eval/store.py gives.
            self.db.close()
            raise

    def _check_version(self) -> None:
        row = self.db.execute("SELECT value FROM meta WHERE key='schema_version'").fetchone()
        if row is None:
            self.db.execute(
                "INSERT INTO meta(key, value) VALUES ('schema_version', ?)", (str(SCHEMA_VERSION),)
            )
            return
        if int(row["value"]) != SCHEMA_VERSION:
            raise RuntimeError(
                f"{self.path} was written by play-store schema version {row['value']}, this "
                f"build is {SCHEMA_VERSION}. Refusing to read it under the wrong meaning."
            )

    def close(self) -> None:
        with self._lock:
            self.db.close()

    def __enter__(self) -> PlayStore:
        return self

    def __exit__(self, *exc: object) -> None:
        self.close()

    def _write(self, statements: Sequence[tuple[str, Sequence[object]]]) -> None:
        with self._lock:
            self.db.execute("BEGIN")
            try:
                for sql, args in statements:
                    self.db.execute(sql, args)
                self.db.execute("COMMIT")
            except Exception:
                self.db.execute("ROLLBACK")
                raise

    def _read(self, sql: str, args: Sequence[object] = ()) -> list[sqlite3.Row]:
        with self._lock:
            return self.db.execute(sql, args).fetchall()

    # -- players -------------------------------------------------------

    def add_human(self, name: str) -> PlayerRow:
        row = PlayerRow(secrets.token_hex(8), "human", name, None, None, None, None, None, now())
        self._insert_player(row)
        return row

    def add_bot(self, identity: AgentRow, name: str) -> PlayerRow:
        """The bot's player row, created the first time it is seated."""
        player_id = bot_id(identity)
        existing = self.player(player_id)
        if existing is not None:
            return existing
        row = PlayerRow(
            player_id,
            "bot",
            name,
            identity.spec,
            identity.family,
            identity.params_hash,
            identity.behaviour_hash,
            identity.checkpoint,
            now(),
        )
        self._insert_player(row)
        return self.player(player_id) or row

    def _insert_player(self, row: PlayerRow) -> None:
        self._write(
            [
                (
                    f"INSERT INTO player({_PLAYER_COLUMNS}) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)"
                    " ON CONFLICT (player_id) DO NOTHING",
                    (
                        row.player_id,
                        row.kind,
                        row.name,
                        row.spec,
                        row.family,
                        row.params_hash,
                        row.behaviour_hash,
                        row.checkpoint,
                        row.created_utc,
                    ),
                )
            ]
        )

    def player(self, player_id: str) -> PlayerRow | None:
        rows = self._read(f"SELECT {_PLAYER_COLUMNS} FROM player WHERE player_id = ?", (player_id,))
        return PlayerRow(*rows[0]) if rows else None

    # -- games ---------------------------------------------------------

    def add_game(self, game: GameRow, players: Sequence[str]) -> None:
        """A new game and its seats, in one transaction."""
        values = (
            game.game_id,
            game.map_name,
            game.n_players,
            game.mode,
            int(game.rated),
            game.assist,
            game.status,
            game.seed,
            game.contract_version,
            game.obs_version,
            game.data_hash,
            game.rules_hash,
            game.git_sha,
            game.client_build,
            game.created_utc,
            game.finished_utc,
            game.final_hash,
        )
        placeholders = ", ".join("?" * len(values))
        self._write(
            [(f"INSERT INTO game({_GAME_COLUMNS}) VALUES ({placeholders})", values)]
            + [
                (
                    "INSERT INTO seat(game_id, seat, player_id) VALUES (?, ?, ?)",
                    (game.game_id, seat, player_id),
                )
                for seat, player_id in enumerate(players)
            ]
        )

    def game(self, game_id: str) -> GameRow | None:
        rows = self._read(f"SELECT {_GAME_COLUMNS} FROM game WHERE game_id = ?", (game_id,))
        return _game(rows[0]) if rows else None

    def seats(self, game_id: str) -> list[SeatRow]:
        rows = self._read(
            "SELECT game_id, seat, player_id, score, routes, tickets_made, tickets_missed,"
            " ticket_points, longest_bonus, longest_trail, rank FROM seat"
            " WHERE game_id = ? ORDER BY seat",
            (game_id,),
        )
        return [SeatRow(*row) for row in rows]

    def actions(self, game_id: str) -> list[ActionRow]:
        rows = self._read(
            "SELECT ply, seat, action, server_utc, think_ms FROM action"
            " WHERE game_id = ? ORDER BY ply",
            (game_id,),
        )
        return [ActionRow(*row) for row in rows]

    def append(
        self,
        game_id: str,
        action: ActionRow,
        *,
        final: Sequence[FinalSeat] = (),
        final_hash: str | None = None,
    ) -> None:
        """Record one decision -- and, with `final`, the end of the game -- atomically."""
        statements: list[tuple[str, Sequence[object]]] = [
            (
                "INSERT INTO action(game_id, ply, seat, action, server_utc, think_ms)"
                " VALUES (?, ?, ?, ?, ?, ?)",
                (
                    game_id,
                    action.ply,
                    action.seat,
                    action.action,
                    action.server_utc,
                    action.think_ms,
                ),
            )
        ]
        if final:
            statements.append(
                (
                    "UPDATE game SET status = 'finished', finished_utc = ?, final_hash = ?"
                    " WHERE game_id = ?",
                    (action.server_utc, final_hash, game_id),
                )
            )
            statements.extend(
                (
                    "UPDATE seat SET score = ?, routes = ?, tickets_made = ?, tickets_missed = ?,"
                    " ticket_points = ?, longest_bonus = ?, longest_trail = ?, rank = ?"
                    " WHERE game_id = ? AND seat = ?",
                    (
                        s.score,
                        s.routes,
                        s.tickets_made,
                        s.tickets_missed,
                        s.ticket_points,
                        s.longest_bonus,
                        s.longest_trail,
                        s.rank,
                        game_id,
                        s.seat,
                    ),
                )
                for s in final
            )
        self._write(statements)

    def games_of(self, player_id: str, limit: int = 50) -> list[GameRow]:
        """A player's games, newest first."""
        rows = self._read(
            f"SELECT {', '.join('g.' + c.strip() for c in _GAME_COLUMNS.split(','))}"
            " FROM game g JOIN seat s ON s.game_id = g.game_id"
            " WHERE s.player_id = ? ORDER BY g.created_utc DESC, g.game_id LIMIT ?",
            (player_id, limit),
        )
        return [_game(row) for row in rows]

    def finished_rated(
        self, map_name: str, n_players: int, rules_hash: str
    ) -> list[tuple[GameRow, list[SeatRow]]]:
        """Every finished rated game of a configuration, with its seats -- what joins the
        rating fit."""
        games = [
            _game(row)
            for row in self._read(
                f"SELECT {_GAME_COLUMNS} FROM game WHERE status = 'finished' AND rated = 1"
                " AND map_name = ? AND n_players = ? AND rules_hash = ?"
                " ORDER BY finished_utc, game_id",
                (map_name, n_players, rules_hash),
            )
        ]
        return [(game, self.seats(game.game_id)) for game in games]

    def version(self) -> tuple[int, str | None]:
        """Finished rated games and the latest finish: changes exactly when a rating can."""
        row = self._read(
            "SELECT COUNT(*), MAX(finished_utc) FROM game WHERE status = 'finished' AND rated = 1"
        )[0]
        return int(row[0]), row[1]


def _game(row: sqlite3.Row) -> GameRow:
    values = dict(row)
    values["rated"] = bool(values["rated"])
    return GameRow(**values)
